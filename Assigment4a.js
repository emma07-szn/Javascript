// function with parameters to multiple two numbers

function multiply(num1,num2){
    let answer=num1*num2
    console.log(`Your answer is ${answer}`)
}

multiply(4,9)


// function with parameters to subtract two numbers
function subtraction(num1,num2){
    let answer=num1-num2
    console.log(`Your answer is ${answer}`)
}


subtraction(10,8)